const norm = (s: string) => s.replace(/Ⅰ/g, "1").replace(/Ⅱ/g, "2").replace(/[\s()（）[\]·ㆍ.,\-_/&]/g, "").toLowerCase();

/** 과목이 속한 모듈 (예: "M3 AI·머신러닝") */
export function moduleOf(track: string, course: string): string | null {
  const mt = MODULAR[track];
  if (!mt) return null;
  const k = norm(course);
  const md = mt.modules.find((x) => x.courses.some((c) => norm(c) === k));
  return md ? `${md.id} ${md.name}` : null;
}

/** 진로 경로: 학생이 고른 것 → 희망 직무와 맞는 첫 경로 → 없음 */
export function modulePath(track: string, jobs: readonly string[], chosen?: string): ModulePath | null {
  const mt = MODULAR[track];
  if (!mt) return null;
  return mt.paths.find((x) => x.label === chosen) ?? mt.paths.find((x) => x.jobs.some((j) => jobs.includes(j))) ?? null;
}

/** 경로에 들어간 모듈의 과목 (정규화한 이름) */
export function pathCourses(track: string, path: ModulePath | null): Set<string> {
  const mt = MODULAR[track];
  if (!mt || !path) return new Set();
  return new Set(mt.modules.filter((x) => path.modules.includes(x.id)).flatMap((x) => x.courses.map(norm)));
}
